// True when every word of `query` starts a word of one of the place's names,
// for example "new y" matches "New York" and "york" matches "York" and
// "New York". Short tokens (under 3 letters) only match a whole name, so "la"
// finds Los Angeles but "pa" does not find Paris.
export function placeMatchesToken(place: Place, token: string): boolean {
  if (token.length < 3) return place.keys.includes(token);
  return place.keys.some((key) => key.split(/\s+/).some((word) => word.startsWith(token)));
}

// A lat/lon bounding box around a point, in degrees.
export function boundingBox(lat: number, lon: number, radiusKm: number) {
  const dLat = radiusKm / 111;
  const dLon = radiusKm / (111 * Math.max(0.1, Math.cos((lat * Math.PI) / 180)));
  return { minLat: lat - dLat, maxLat: lat + dLat, minLon: lon - dLon, maxLon: lon + dLon };
}
